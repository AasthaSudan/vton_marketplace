// Generates the database seed and the pricing parity tests from the Dart
// code, so the backend can never drift from the app:
//
//   * supabase/seed/10_catalog.generated.sql — sellers, products, variants,
//     categories, banners and try-on model photos from the mock catalogue;
//   * supabase/tests/database/90_pricing_parity.generated.test.sql — pgTAP
//     checks that the SQL money maths gives the same answers as Dart.
//
// The files are golden files: this test fails when they are out of date.
// Regenerate with:
//   flutter test --update-goldens test/tool/backend_fixtures_test.dart
